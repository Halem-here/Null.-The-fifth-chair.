#!/usr/bin/env python3
"""Build the offline Roman Urdu catalogue from editable locale JSON parts."""
from __future__ import annotations
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
LOCALE = ROOT / "locales" / "roman-urdu"
OUTPUT = ROOT / "js" / "data-locale.js"

entries: dict[str, str] = {}
patterns: list[dict[str, str]] = []

for path in sorted(LOCALE.glob("*.json")):
    data = json.loads(path.read_text(encoding="utf-8"))
    for key, value in data.items():
        if key == "@templates":
            for template in value.values():
                if not isinstance(template, dict) or not template.get("sourceRegex") or not template.get("translationTemplate"):
                    continue
                patterns.append({"sourceRegex": template["sourceRegex"], "translationTemplate": template["translationTemplate"], "source": path.name})
            continue
        if key == "@patterns":
            # Keep only patterns that can be matched against an English source string.
            for source, translation in value.items():
                if isinstance(translation, str) and "{" in source and "}" in source:
                    patterns.append({"sourceTemplate": source, "translationTemplate": translation, "source": path.name})
            continue
        if not isinstance(value, str):
            continue
        if "{" in key and "}" in key:
            patterns.append({"sourceTemplate": key, "translationTemplate": value, "source": path.name})
        else:
            entries[key] = value

payload = {"entries": entries, "patterns": patterns}
(LOCALE / "combined.json").write_text(json.dumps(payload, ensure_ascii=False, indent=2) + "\n", encoding="utf-8")
OUTPUT.write_text(
    "/* Generated by tools/build-locale.py from locales/roman-urdu/*.json. */\n"
    "(function (root) { root.NULL_UR = " + json.dumps(payload, ensure_ascii=False, separators=(",", ":")) + "; })(typeof window !== 'undefined' ? window : globalThis);\n",
    encoding="utf-8",
)
print(f"Wrote {OUTPUT.relative_to(ROOT)}: {len(entries)} exact entries, {len(patterns)} patterns")
